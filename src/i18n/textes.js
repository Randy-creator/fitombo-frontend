export function creerTextes() {
  return {
    langue: 'fr',
    lire(cle) { return (this.langue === 'mg' ? mg : fr)[cle] ?? cle },
    nombre(valeur) { return new Intl.NumberFormat(this.langue === 'mg' ? 'mg-MG' : 'fr-MG').format(valeur) },
    erreur(erreur, connexion = false) {
      const cle = {
        400: 'invalide', 401: connexion ? 'refus' : 'finSession', 403: 'indisponible',
        404: 'indisponible', 409: 'conflit', 429: 'limite',
      }[erreur.status]
      return this.lire(cle || (erreur.status ? 'incident' : 'reseau'))
    },
  }
}
